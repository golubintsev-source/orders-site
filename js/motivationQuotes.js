function startOfLocalHourMs() {
  const d = new Date();
  d.setMinutes(0, 0, 0);
  d.setMilliseconds(0);
  return d.getTime();
}

/**
 * Одна и та же фраза для всех в течение локального календарного часа; при смене часа — другая.
 */
export function getHourlyMotivationPhrase() {
  const hourKey = Math.floor(startOfLocalHourMs() / (1000 * 60 * 60));
  const idx = ((hourKey % PHRASES.length) + PHRASES.length) % PHRASES.length;
  return PHRASES[idx];
}

export function applyHourlyMotivationToElement(el) {
  if (!el) return;
  el.textContent = getHourlyMotivationPhrase();
}

/**
 * Обновлять текст в начале каждого нового локального часа (если вкладка открыта).
 */
export function scheduleHourlyMotivationUpdates(updateFn) {
  updateFn();
  function msUntilNextHour() {
    const now = new Date();
    const next = new Date(now);
    next.setHours(next.getHours() + 1, 0, 0, 0);
    return Math.max(0, next.getTime() - now.getTime());
  }
  setTimeout(() => {
    updateFn();
    setInterval(updateFn, 60 * 60 * 1000);
  }, msUntilNextHour());
}
