-- Этот скрипт:
--   ✅ DROP INDEX — удаляет только индекс, не строки таблицы
--   ❌ НЕ делает DELETE / TRUNCATE / DROP TABLE
--   ❌ НЕ меняет и не скрывает данные (нет UPDATE deleted_at)
--
-- Выполнить в Supabase SQL Editor (postgres). Можно повторно.
-- =============================================================================

